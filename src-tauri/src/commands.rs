// Spawn the sidecar and collect full stdout/stderr/exit. Err only on spawn failure;
// callers decide how to handle non-zero exit codes (doctor wants the body either way).
async fn run_sidecar(app: &AppHandle, args: &[&str]) -> Result<(String, String, i32), String> {
    let output = app
        .shell()
        .sidecar("claude-sync")
        .map_err(|e| e.to_string())?
        .args(args)
        .output()
        .await
        .map_err(|e| e.to_string())?;

    let stdout = String::from_utf8_lossy(&output.stdout).to_string();
    let stderr = String::from_utf8_lossy(&output.stderr).to_string();
    let code = output.status.code().unwrap_or(-1);
    Ok((stdout, stderr, code))
}

fn fail_message(stderr: &str, stdout: &str) -> String {
    let s = stderr.trim();
    if !s.is_empty() {
        return s.to_string();
    }
    let o = stdout.trim();
    if !o.is_empty() {
        return o.to_string();
    }
    "claude-sync exited with non-zero status".to_string()
}

// claude-sync 0.x prints "Not initialized. Run `claude-sync init <remote>` first."
// on stdout with exit code 0 for read-only commands (status, doctor, pull). The
// UI needs an Err for that case so App.tsx can route to InitScreen — otherwise
// parse_status produces an empty StatusResult and the user lands on a broken
// main screen with no way out. Match leniently on the stdout prefix.
fn is_not_initialized_stdout(stdout: &str) -> bool {
    stdout.trim_start().starts_with("Not initialized")
}

// Defense in depth: the capability validator already rejects control chars and
// >2048-char strings, but we also sanity-check the URL in Rust so a future
// capability widening can't accidentally let bad input through to git.
fn validate_remote_url(remote: &str) -> Result<(), String> {
    if remote.is_empty() {
        return Err("Remote URL is empty".to_string());
    }
    if remote.len() > 2048 {
        return Err("Remote URL is too long (max 2048 chars)".to_string());
    }
    if remote.chars().any(|c| c.is_control()) {
        return Err("Remote URL contains control characters".to_string());
    }
    Ok(())
}

#[tauri::command]
pub async fn init(app: AppHandle, remote: String) -> Result<String, String> {
    validate_remote_url(&remote)?;
    let (stdout, stderr, code) = run_sidecar(&app, &["init", remote.as_str()]).await?;
    if code != 0 {
        return Err(fail_message(&stderr, &stdout));
    }
    Ok(stdout.trim().to_string())
}

#[tauri::command]
pub async fn status(app: AppHandle) -> Result<StatusResult, String> {
    let (stdout, stderr, code) = run_sidecar(&app, &["status"]).await?;
    if code != 0 {
        return Err(fail_message(&stderr, &stdout));
    }
    // Sidecar prints "Not initialized..." on stdout with exit 0 — translate to Err
    // so App.tsx can route to InitScreen instead of rendering an empty StatusResult.
    if is_not_initialized_stdout(&stdout) {
        return Err(stdout.trim().to_string());
    }
    Ok(parse::parse_status(&stdout))
}

// Parse the stdout of `git ls-remote origin <branch>`.
// Format: "<sha>\t<refname>\n" per ref, or empty when the ref does not exist.
// Returns the SHA of the first matching line, or None if stdout is empty.
// Pure function — no I/O — so unit tests exercise it without git.
fn parse_ls_remote_output(stdout: &str) -> Option<String> {
    let line = stdout.lines().next()?;
    let sha = line.split('\t').next()?.trim();
    if sha.is_empty() {
        return None;
    }
    Some(sha.to_string())
}

// Resolve the current branch via `git rev-parse --abbrev-ref HEAD`.
// Returns "HEAD" for detached HEAD; any spawn/exit failure is surfaced
// as a push_unverified-prefixed Err so the user knows verification
// could not run, instead of silently falling back to "main" and
// comparing against the wrong branch on a master-default repo.
async fn current_branch(claude_dir: &Path) -> Result<String, String> {
    let output = tokio::process::Command::new("git")
        .arg("-C")
        .arg(claude_dir)
        .args(["rev-parse", "--abbrev-ref", "HEAD"])
        .output()
        .await
        .map_err(|e| format!("push_unverified: rev-parse --abbrev-ref HEAD failed: {e}"))?;
    if !output.status.success() {
        let stderr = String::from_utf8_lossy(&output.stderr);
        return Err(format!(
            "push_unverified: rev-parse --abbrev-ref HEAD failed: {}",
            stderr.trim()
        ));
    }
    let name = String::from_utf8_lossy(&output.stdout).trim().to_string();
    if name.is_empty() {
        return Err("push_unverified: rev-parse --abbrev-ref HEAD returned empty output".to_string());
    }
    // "HEAD" (detached) is still a valid String — ls_remote_sha will look up
    // origin/HEAD which is typically the remote default branch; SHA mismatch
    // (or "no ref" Err) then produces a correct push_unverified outcome.
    Ok(name)
}

// Invoke `git -C <claude_dir> rev-parse HEAD` and return the full SHA string.
// Err with stable "push_unverified:" prefix on failure.
async fn local_head_sha(claude_dir: &Path) -> Result<String, String> {
    let output = tokio::process::Command::new("git")
        .arg("-C")
        .arg(claude_dir)
        .args(["rev-parse", "HEAD"])
        .output()
        .await
        .map_err(|e| format!("push_unverified: rev-parse HEAD failed: {e}"))?;
    if !output.status.success() {
        let stderr = String::from_utf8_lossy(&output.stderr);
        return Err(format!(
            "push_unverified: rev-parse HEAD failed: {}",
            stderr.trim()
        ));
    }
    let sha = String::from_utf8_lossy(&output.stdout).trim().to_string();
    if sha.is_empty() {
        return Err("push_unverified: rev-parse HEAD returned empty output".to_string());
    }
    Ok(sha)
}

// Invoke `git -C <claude_dir> ls-remote origin <branch>` with a 10-second
// network timeout. Returns:
//   Ok(Some(sha)) — the remote has the ref at that SHA
//   Ok(None)      — the remote has no such ref (empty repo or branch not pushed)
//   Err(...)      — spawn error, non-zero exit, or timeout
async fn ls_remote_sha(claude_dir: &Path, branch: &str) -> Result<Option<String>, String> {
    let fut = tokio::process::Command::new("git")
        // v0.2.7 WARNING #1 fix — block credential prompts so a missing GCM
        // doesn't make us wait the full 10-second timeout. GIT_TERMINAL_PROMPT=0
        // makes git fail fast instead of asking on stdin; GIT_ASKPASS=echo is
        // belt-and-suspenders for tools that bypass GIT_TERMINAL_PROMPT.
        .env("GIT_TERMINAL_PROMPT", "0")
        .env("GIT_ASKPASS", "echo")
        .arg("-C")
        .arg(claude_dir)
        .args(["ls-remote", "origin", branch])
        .output();
    let output = tokio::time::timeout(std::time::Duration::from_secs(10), fut)
        .await
        .map_err(|_| "push_unverified: ls-remote timed out after 10s".to_string())?
        .map_err(|e| format!("push_unverified: ls-remote failed: {e}"))?;
    if !output.status.success() {
        let stderr = String::from_utf8_lossy(&output.stderr);
        return Err(format!(
            "push_unverified: ls-remote failed: {}",
            stderr.trim()
        ));
    }
    let stdout = String::from_utf8_lossy(&output.stdout).to_string();
    Ok(parse_ls_remote_output(&stdout))
}

#[tauri::command]
pub async fn push(app: AppHandle, message: Option<String>) -> Result<PushResult, String> {
    let mut args: Vec<&str> = vec!["push"];
    if let Some(ref m) = message {
        if !m.is_empty() {
            args.push("-m");
            args.push(m.as_str());
        }
    }
    let (stdout, stderr, code) = run_sidecar(&app, &args).await?;
    if code != 0 {
        return Err(fail_message(&stderr, &stdout));
    }
    // "Not initialized" comes back on stdout w/ non-zero exit in the spec, but be defensive.
    if is_not_initialized_stdout(&stdout) {
        return Err(stdout.trim().to_string());
    }
    let result = parse::parse_push(&stdout);

    // "Nothing to push" — sidecar never actually called git push, so the
    // remote-tracking ref was never expected to change. Skip verification.
    if result.nothing_to_push {
        return Ok(result);
    }

    // v0.2.7 — verify push reached GitHub by querying origin directly.
    // `git ls-remote origin <branch>` asks GitHub for the current ref SHA
    // without depending on the sidecar's status implementation. This closes
    // the v0.2.6 escape hatch where the sidecar's missing
    // refs/remotes/origin/<branch> caused ahead=0 to be reported spuriously.
    //
    // All three subprocess calls (current_branch / local_head_sha / ls_remote_sha)
    // are independent of the sidecar. Failure is always surfaced as a
    // "push_unverified:" prefixed error so the FE push-unverified toast fires.
    let claude_dir = resolve_claude_dir().map_err(|e| format!("push_unverified: {e}"))?;
    let branch = current_branch(&claude_dir).await?;
    let local_head = local_head_sha(&claude_dir).await?;
    let remote_sha = ls_remote_sha(&claude_dir, &branch).await?;
    match remote_sha {
        None => Err(format!(
            "push_unverified: origin has no '{branch}' ref — push never reached GitHub"
        )),
        Some(ref s) if s == &local_head => Ok(result),
        Some(ref s) => {
            let remote_short = &s[..s.len().min(7)];
            let local_short = &local_head[..local_head.len().min(7)];
            Err(format!(
                "push_unverified: origin/{branch} is at {remote_short} but local HEAD is {local_short}"
            ))
        }
    }
}

#[tauri::command]
pub async fn pull(app: AppHandle) -> Result<PullResult, String> {
    let (stdout, stderr, code) = run_sidecar(&app, &["pull"]).await?;
    // Conflict case may exit non-zero but still produces a parseable body — treat as success.
    if code != 0 && !stdout.contains("Merged with conflicts") {
        return Err(fail_message(&stderr, &stdout));
    }
    // Same "exit 0 + Not initialized on stdout" trap as status — surface to UI.
    if is_not_initialized_stdout(&stdout) {
        return Err(stdout.trim().to_string());
    }
    Ok(parse::parse_pull(&stdout))
}

#[tauri::command]
pub async fn doctor(app: AppHandle) -> Result<DoctorResult, String> {
    // Doctor returns exit 1 when overall FAIL; we still want the structured body for the UI.
    let (stdout, _stderr, _code) = run_sidecar(&app, &["doctor"]).await?;
    Ok(parse::parse_doctor(&stdout))
}

// Resolve `~/.claude/` using the same env-var precedence as the sidecar's
// `commands::util::home_dir`: HOME first, then USERPROFILE. Honors env overrides
// so tests can redirect the lookup without touching the real user profile.
fn resolve_claude_dir() -> Result<PathBuf, String> {
    let home = std::env::var_os("HOME")
        .or_else(|| std::env::var_os("USERPROFILE"))
        .map(PathBuf::from)
        .filter(|p| !p.as_os_str().is_empty())
        .ok_or_else(|| "could not determine home directory".to_string())?;
    Ok(home.join(".claude"))
}

// Rewrite the `url = ...` line inside `[remote "origin"]` of a git config text.
// We only mutate the first url inside the first origin section — anything else
// is left untouched so we don't accidentally clobber comments, push URLs, or
// other remotes. Returns Err if no origin section or no url line is present.
fn rewrite_origin_url(config: &str, new_url: &str) -> Result<String, String> {
    let mut out = String::new();
    let mut in_origin = false;
    let mut url_replaced = false;
    let mut found_origin = false;
    let trailing_newline = config.ends_with('\n');
    for line in config.lines() {
        let trimmed = line.trim_start();
        if trimmed.starts_with('[') {
            // Section header — switch context, preserve original line verbatim.
            in_origin = trimmed.trim_end() == "[remote \"origin\"]";
            if in_origin {
                found_origin = true;
            }
            out.push_str(line);
            out.push('\n');
            continue;
        }
        if in_origin && !url_replaced {
            // Match `url = ...` / `url=...` (git is case-sensitive on keys).
            let after_ws = line.trim_start();
            if let Some(rest) = after_ws.strip_prefix("url") {
                let rest = rest.trim_start();
                if rest.starts_with('=') {
                    let leading_ws: String =
                        line.chars().take_while(|c| c.is_whitespace()).collect();
                    out.push_str(&leading_ws);
                    out.push_str("url = ");
                    out.push_str(new_url);
                    out.push('\n');
                    url_replaced = true;
                    continue;
                }
            }
        }
        out.push_str(line);
        out.push('\n');
    }
    if !found_origin {
        return Err("origin remote not found in git config".to_string());
    }
    if !url_replaced {
        return Err("origin url not found in git config".to_string());
    }
    // Preserve the original file's trailing-newline state — `lines()` strips it.
    if !trailing_newline && out.ends_with('\n') {
        out.pop();
    }
    Ok(out)
}

// Atomically replace the `[remote "origin"]` URL in `~/.claude/.git/config`.
// Pure Rust (no shell out, no git2 dep) — we just read-modify-write the INI file.
// Writes via a sibling tempfile + rename so a crash mid-write can't corrupt the
// user's git config.
#[tauri::command]
pub async fn set_remote(new_url: String) -> Result<(), String> {
    validate_remote_url(&new_url)?;
    let claude_dir = resolve_claude_dir()?;
    let config_path = claude_dir.join(".git").join("config");
    if !config_path.exists() {
        return Err(
            "Not initialized. Run `claude-sync init <remote>` first.".to_string(),
        );
    }
    let original = std::fs::read_to_string(&config_path)
        .map_err(|e| format!("read {}: {e}", config_path.display()))?;
    let updated = rewrite_origin_url(&original, &new_url)?;
    if updated == original {
        // No-op: nothing to write, no risk to take.
        return Ok(());
    }
    // Per-call unique tempfile name so two concurrent set_remote invocations
    // (rare, but possible if the user double-clicks the Update button while
    // the modal hasn't disabled yet) don't trample each other's write. PID +
    // nanos is enough entropy for the realistic concurrency we expect here
    // without pulling in the `tempfile` crate.
    let nanos = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.subsec_nanos())
        .unwrap_or(0);
    let tmp_name = format!("config.tmp.{}.{}", std::process::id(), nanos);
    let tmp_path = config_path.with_file_name(tmp_name);
    std::fs::write(&tmp_path, &updated)
        .map_err(|e| format!("write {}: {e}", tmp_path.display()))?;
    std::fs::rename(&tmp_path, &config_path).map_err(|e| {
        // Best-effort cleanup so we don't leave a stray config.tmp.* behind.
        let _ = std::fs::remove_file(&tmp_path);
        format!("replace {}: {e}", config_path.display())
    })?;
    Ok(())
}

// Write a `.stowignore` file inside `claude_dir` containing the recommended
// default body. Atomic write (sibling tempfile + rename) so a crash mid-write
// can't leave a half-written `.stowignore` that the sidecar would then load.
//
// Contract:
//   - Err("claude_dir_not_found")  if claude_dir itself does not exist.
//     We deliberately do NOT mkdir it — claude-sync requires the user to
//     have a real `~/.claude/` from claude code; creating an empty one would
//     mask a much weirder bug.
//   - Err("stowignore_exists")     if `.stowignore` already exists. We never
//     overwrite — the user may have hand-edited it (e.g. the v0.2.2 hotfix
//     dogfood path) and clobbering would be hostile.
//   - Ok(())                       on a successful first-time write.
//
// Extracted out of `create_default_stowignore` so unit tests can target a
// temp directory without monkey-patching HOME/USERPROFILE (env-var mutation
// in parallel tests is racy + unsafe in 2024-edition Rust).
fn create_default_stowignore_at(claude_dir: &Path) -> Result<(), String> {
    if !claude_dir.exists() {
        return Err("claude_dir_not_found".to_string());
    }
    let target = claude_dir.join(".stowignore");
    if target.exists() {
        return Err("stowignore_exists".to_string());
    }
    // Same tempfile-naming scheme as set_remote — PID + nanos is enough
    // entropy for the realistic concurrency we expect (the button is
    // debounced in the UI but defense-in-depth is cheap).
    let nanos = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.subsec_nanos())
        .unwrap_or(0);
    let tmp_name = format!(".stowignore.tmp.{}.{}", std::process::id(), nanos);
    let tmp_path = claude_dir.join(tmp_name);
    std::fs::write(&tmp_path, DEFAULT_STOWIGNORE)
        .map_err(|e| format!("write {}: {e}", tmp_path.display()))?;
    std::fs::rename(&tmp_path, &target).map_err(|e| {
        // Best-effort cleanup so we don't leave a stray .stowignore.tmp.* behind.
        let _ = std::fs::remove_file(&tmp_path);
        format!("replace {}: {e}", target.display())
    })?;
    Ok(())
}

// Public command — resolves ~/.claude/ then delegates to the helper above.
// Surfaced to the FE so the ErrorBanner secret-scan action button can call
// this directly when the sidecar's init refuses on secret findings.
#[tauri::command]
pub async fn create_default_stowignore() -> Result<(), String> {
    let claude_dir = resolve_claude_dir()?;
    create_default_stowignore_at(&claude_dir)
}

// Return the contents of ~/.claude/.stowignore so the UI can show the user
// exactly which paths are excluded from sync. v0.2.4 dogfood report: a new
// user had no way to verify their per-machine directories (projects/,
// file-history/, ...) were actually being skipped — the only signal was the
// "excluded: stow N" count, which is opaque.
//
// Contract:
//   - Ok("")                     when ~/.claude/.stowignore does not exist
//                                (treated as "no exclusions" rather than an error)
//   - Ok(<file body>)            normal case
//   - Err(<read error>)          unreadable file (permissions, etc.)
//
// We intentionally read the file every call rather than caching — the user
// may hand-edit `.stowignore` between modal opens and the modal must reflect
// the current state.
#[tauri::command]
pub async fn read_stowignore() -> Result<String, String> {
    let claude_dir = resolve_claude_dir()?;
    let path = claude_dir.join(".stowignore");
    if !path.exists() {
        return Ok(String::new());
    }
    std::fs::read_to_string(&path).map_err(|e| format!("read {}: {e}", path.display()))
}

