    // Small per-test temp dir without pulling in the `tempfile` crate. PID +
    // nanos + thread-id keeps it unique across parallel cargo-test threads.
    fn make_tempdir(tag: &str) -> PathBuf {
        let nanos = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .map(|d| d.as_nanos())
            .unwrap_or(0);
        let thread = std::thread::current();
        // Replace any path-unfriendly chars in thread name with '_'.
        let safe_thread: String = thread
            .name()
            .unwrap_or("unnamed")
            .chars()
            .map(|c| if c.is_ascii_alphanumeric() { c } else { '_' })
            .collect();
        let dir = std::env::temp_dir().join(format!(
            "csui-test-{}-{}-{}-{}",
            tag,
            std::process::id(),
            safe_thread,
            nanos
        ));
        std::fs::create_dir_all(&dir).expect("make_tempdir: create_dir_all");
        dir
    }

