const DEFAULT_STOWIGNORE: &str = "# claude-sync .stowignore \u{2014} generated by claude-sync-ui\n# Files and directories NOT pushed to the remote repository.\n\n# Tokens and credentials (NEVER sync)\n.credentials.json\n\n# Per-machine working state (often contains secrets)\nhistory.jsonl\nfile-history/\nshell-snapshots/\nprojects/\ntodos/\nsessions/\nsession-env/\n\n# Caches\ncache/\nimage-cache/\npaste-cache/\nbackups/\nide/\n\n# Daemon runtime\ndaemon/\ndaemon.lock\ndaemon.log\ndaemon.status.json\n\n# Cleanup markers\n.last-cleanup\n.serena/\nmcp-needs-auth-cache.json\n\n# Debug / job runtime\ndebug/\njobs/\n\n# Marketplace plugins with example credentials\nplugins/marketplaces/thedotmack/cursor-hooks/STANDALONE-SETUP.md\n";

